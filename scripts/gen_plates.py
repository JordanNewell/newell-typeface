#!/usr/bin/env python3
"""Generate anatomy plates for newell.ink (index.html).

The hero alphabet (A E M N R S W) rendered as annotated plates. Glyph
art = the live webfont (same as everywhere on the site); the anatomy
counts come straight from src/newell/glyphs.py — the plates are
generated, not hand-drawn, same as the alphabet itself.

Usage:
  python scripts/gen_plates.py             # print fragment to stdout
  python scripts/gen_plates.py --splice    # replace markers in index.html
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src" / "newell"))
from glyphs import GLYPHS  # noqa: E402

HERO = ["A", "E", "M", "N", "R", "S", "W"]

# One-line role notes, mirroring SPEC.md section 7. The S note IS the
# ruling — keep it on the record.
NOTES = {
    "A": "Two diagonals meeting at an apex; one rail for the bar.",
    "E": "One rail on the left; three rails — top, middle, bottom.",
    "M": "Two outer rails; two diagonals meeting at center.",
    "N": "The signature. Two rails; one diagonal, top to bottom.",
    "R": "One rail; the leg is the N diagonal doing double duty.",
    "S": "Z's diagonal wearing S's name. Half-bars for terminals.",
    "W": "Four diagonals. No rails at all.",
}

START = "<!-- PLATES:START"
END = "<!-- PLATES:END -->"


def counts(letter):
    g = next(x for x in GLYPHS if x["name"] == letter)
    rails = sum(1 for p in g["primitives"] if p["type"] in ("hline", "vline"))
    diags = sum(1 for p in g["primitives"] if p["type"] == "diag")
    return rails, diags


def plate(letter):
    rails, diags = counts(letter)
    return f'''      <div class="plate">
        <div class="plate-glyph">{letter}</div>
        <div class="plate-anno">
          <span class="plate-letter">{letter}</span>
          <span class="plate-counts">{rails} RAILS · {diags} DIAGONALS</span>
          <span class="plate-note">{NOTES[letter]}</span>
        </div>
      </div>'''


def fragment():
    body = "\n".join(plate(L) for L in HERO)
    return (
        f"{START} (generated by scripts/gen_plates.py — do not edit by hand) -->\n"
        f"{body}\n"
        f"{END}"
    )


def splice():
    path = ROOT / "index.html"
    html = path.read_text(encoding="utf-8")
    if START not in html or END not in html:
        sys.exit("index.html has no PLATES markers — add the section skeleton first")
    head = html.index(START)
    tail = html.index(END) + len(END)
    path.write_text(html[:head] + fragment() + html[tail:], encoding="utf-8", newline="\n")
    print(f"spliced {len(HERO)} plates into {path.name}")


if __name__ == "__main__":
    for L in HERO:
        rails, diags = counts(L)
        print(f"  {L}: {rails} rails, {diags} diagonals")
    if "--splice" in sys.argv:
        splice()
    else:
        print()
        print(fragment())
